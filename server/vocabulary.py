def label_to_korean(label):
    """
    숫자 라벨을 NLP에서 사용할 대표 한국어 단어로 변환

    예:
    7  -> "나"
    68 -> "저녁"
    72 -> "원하다"
    """
    return LABEL_TO_KOREAN.get(label, f"알수없음({label})")


def labels_to_korean(labels):
    """
    여러 개의 숫자 라벨을 한국어 단어 리스트로 변환

    예:
    [7, 68, 16]
    -> ["나", "저녁", "먹다"]
    """
    return [label_to_korean(label) for label in labels]


def get_meanings(label):
    """
    해당 수어 라벨이 가질 수 있는 모든 의미 반환

    예:
    14
    -> ["같다", "동일", "마찬가지", "맞다"]
    """
    return LABEL_MEANINGS.get(label, [])

